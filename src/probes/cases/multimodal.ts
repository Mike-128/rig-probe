import { DEFAULT_IMAGE_URL } from "../../profile";
import { defineProbe } from "../types";
import { CITATION_DOC, codewordPdf, PDF_CODEWORD, solidPng } from "../fixtures";
import { base, blocksOf, excerpt, textOf } from "./_util";

export const multimodal = [
  defineProbe({
    id: "TC-MM-01",
    title: "Image input (base64)",
    category: "multimodal",
    purpose: "Checks an inline base64 image reaches the model intact. Gateways with body-size limits or content inspection sometimes damage or reject large JSON bodies.",
    surface: "POST /v1/messages · image block, source.type base64",
    steps: ["Generate a solid red 64×64 PNG.", "Send it with a request to name its color in one word."],
    expected: "The reply says red.",
    cost: "low",
    feature: "vision",
    async run(ctx) {
      const png = solidPng(64, 64, [220, 20, 20]).toString("base64");
      const res = await ctx.client.messages.create({
        ...base(ctx),
        messages: [
          {
            role: "user",
            content: [
              { type: "image", source: { type: "base64", media_type: "image/png", data: png } },
              { type: "text", text: "What color is this image? Answer with one word." },
            ],
          },
        ],
      });
      ctx.check("Model identifies the color as red", /red/i.test(textOf(res)), excerpt(textOf(res)));
    },
  }),

  defineProbe({
    id: "TC-MM-02",
    title: "Image input (URL)",
    category: "multimodal",
    purpose: "Checks URL image sources, which Anthropic fetches server-side. Useful to confirm the platform supports it; a failure here can also come from the image host.",
    surface: "POST /v1/messages · image block, source.type url",
    steps: ["Send an image by URL (configurable) with a request to describe it."],
    expected: "HTTP 200 with a description. With the default image (dice), the description mentions dice.",
    cost: "low",
    feature: "vision",
    async run(ctx) {
      const url = ctx.profile.imageUrl;
      const res = await ctx.client.messages.create({
        ...base(ctx),
        messages: [
          {
            role: "user",
            content: [
              { type: "image", source: { type: "url", url } },
              { type: "text", text: "Describe this image in one sentence." },
            ],
          },
        ],
      });
      ctx.check("URL image accepted and described", textOf(res).length > 0, excerpt(textOf(res)));
      if (url === DEFAULT_IMAGE_URL) ctx.advise("Description matches the default image (dice)", /dice|die\b/i.test(textOf(res)), excerpt(textOf(res)));
    },
  }),

  defineProbe({
    id: "TC-MM-03",
    title: "PDF document (base64)",
    category: "multimodal",
    purpose: "Checks PDF input. The PDF is generated by this tool and contains a codeword the model can only know by reading it.",
    surface: "POST /v1/messages · document block, source.type base64, application/pdf",
    steps: ["Generate a one-page PDF containing the codeword PELICAN-42.", "Ask the model for the codeword."],
    expected: "The reply contains PELICAN-42.",
    cost: "low",
    async run(ctx) {
      const pdf = codewordPdf().toString("base64");
      const res = await ctx.client.messages.create({
        ...base(ctx),
        messages: [
          {
            role: "user",
            content: [
              { type: "document", source: { type: "base64", media_type: "application/pdf", data: pdf } },
              { type: "text", text: "What is the secret codeword in this document? Reply with just the codeword." },
            ],
          },
        ],
      });
      ctx.check(`Model read the codeword from the PDF (${PDF_CODEWORD})`, textOf(res).includes(PDF_CODEWORD), excerpt(textOf(res)));
    },
  }),

  defineProbe({
    id: "TC-MM-04",
    title: "Citations from a plain-text document",
    category: "multimodal",
    purpose: "Checks citations: the response is split into text blocks that point back to the exact passage supporting each claim.",
    surface: "POST /v1/messages · document block (text) with citations.enabled",
    steps: ["Send a short plain-text document with citations enabled.", "Ask where the facility is located."],
    expected: "The answer names Reykjavik and at least one text block carries a citation quoting the document.",
    cost: "low",
    async run(ctx) {
      const res = await ctx.client.messages.create({
        ...base(ctx),
        messages: [
          {
            role: "user",
            content: [
              { type: "document", source: { type: "text", media_type: "text/plain", data: CITATION_DOC.text }, title: CITATION_DOC.title, citations: { enabled: true } },
              { type: "text", text: "Where is the Rig Probe test facility located? Answer in one sentence." },
            ],
          },
        ],
      });
      const cited = blocksOf(res, "text").flatMap((b) => (Array.isArray(b.citations) ? (b.citations as { cited_text?: string; type?: string }[]) : []));
      ctx.check("Answer names Reykjavik", textOf(res).includes(CITATION_DOC.answer), excerpt(textOf(res)));
      ctx.check("Response carries citations", cited.length > 0, `${cited.length} citation(s)`);
      ctx.advise("A citation quotes the supporting passage", cited.some((c) => c.cited_text?.includes(CITATION_DOC.answer)), excerpt(cited.map((c) => c.cited_text).join(" | ")));
      ctx.advise("Citation location type is char_location", cited.some((c) => c.type === "char_location"), cited.map((c) => c.type).join(", "));
    },
  }),
];
